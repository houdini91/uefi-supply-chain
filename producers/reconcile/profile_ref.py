#!/usr/bin/env python3
"""profile_ref — an independent reference implementation of the normalized-hash profile.

Written from `docs/normalized-module-hash-profile.md` sections 3 and 4 ALONE, deliberately
without consulting `ffs.canon_unrebase`, and with NO third-party dependency (no pefile).

Why it exists
-------------
Conformance vectors generated by the implementation they are meant to test prove nothing --
they can only confirm that an implementation agrees with itself. This is the second
implementation the vectors are generated from and checked against, so a disagreement between
this and `canon_unrebase` is a real finding rather than a tautology.

It is also the honest test of whether the profile document is implementable by a stranger.
Every place the document did not say enough is recorded in GUESSES below, with the choice made.
Each entry is a defect in the document, not a note about this file.
"""
import hashlib
import struct

# ---------------------------------------------------------------------------
